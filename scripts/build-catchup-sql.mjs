/**
 * Bundles the recent migrations into one block somebody can paste once.
 *
 * The Supabase SQL editor runs a paste as a single transaction, so a
 * statement that fails because it was already applied rolls back everything
 * above it. Every migration from the start file onwards is written to be
 * re-runnable — `if not exists` on tables and columns, `drop policy if
 * exists` before each policy — which is what makes concatenating them safe
 * whether or not some have already been run.
 *
 * That matters because the person applying these is doing it on a phone, and
 * nine separate pastes in the right order is how one gets missed.
 *
 * Run: node scripts/build-catchup-sql.mjs [firstFile]
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const DIR = "supabase/migrations";
const OUT = "supabase/catchup.sql";
const FROM = process.argv[2] ?? "0116_payment_plans.sql";

const files = readdirSync(DIR)
  .filter((f) => f.endsWith(".sql"))
  .sort()
  .filter((f) => f >= FROM);

if (files.length === 0) {
  console.error(`Nothing at or after ${FROM}`);
  process.exit(1);
}

const parts = files.map(
  (file) =>
    `-- ===========================================================================\n` +
    `-- ${file}\n` +
    `-- ===========================================================================\n` +
    readFileSync(join(DIR, file), "utf8").trimEnd()
);

writeFileSync(
  OUT,
  `-- GENERATED by scripts/build-catchup-sql.mjs — do not edit by hand.\n` +
    `--\n` +
    `-- Migrations ${files[0]} through ${files[files.length - 1]}, in order, in one\n` +
    `-- paste. Safe to run more than once: every statement is guarded, so the\n` +
    `-- ones already applied do nothing rather than failing and rolling back the\n` +
    `-- ones that are not.\n\n` +
    parts.join("\n\n") +
    `\n\nnotify pgrst, 'reload schema';\n`
);

console.log(`wrote ${OUT} with ${files.length} migrations (${files[0]} .. ${files[files.length - 1]})`);
