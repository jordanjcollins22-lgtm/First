#!/usr/bin/env python3
"""
Turns Jordan's production rate workbook into src/lib/production-rates-seed.ts.

  python3 -I scripts/production-rates-seed.py /mnt/project-files/pricing/landscaping_production_rates.xlsx

Reads the "Production Rates" and "Logistics" sheets (values, not formulas)
and writes a typed seed file. Every rate in the workbook is provisional; the
seed is only the starting point the variables page edits from.
"""

import json
import re
import sys

import openpyxl

UNITS = {"SF", "LF", "EA", "CY", "TON"}


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def main(path: str, out: str) -> None:
    wb = openpyxl.load_workbook(path, data_only=True, read_only=True)
    rates = []
    seen = set()
    for row in wb["Production Rates"].iter_rows(min_row=2, values_only=True):
        category, task, unit, upm = row[0], row[1], row[2], row[3]
        if not task:
            continue
        unit = str(unit).strip().upper()
        if unit not in UNITS:
            raise SystemExit(f"Unknown unit {unit!r} on {task!r}")
        key = f"{slug(category)}.{slug(task)}"
        if key in seen:
            raise SystemExit(f"Duplicate task {key}")
        seen.add(key)
        rates.append({"key": key, "category": str(category).strip(), "task": str(task).strip(), "unit": unit, "unitsPerLaborMinute": float(upm)})

    logistics = []
    for row in wb["Logistics"].iter_rows(min_row=2, values_only=True):
        task, measurement, minutes, notes = row[0], row[1], row[2], row[3]
        if not task:
            continue
        logistics.append({"task": str(task).strip(), "measurement": str(measurement).strip(), "minutes": minutes, "notes": str(notes or "").strip()})

    lines = [
        "/**",
        " * Jordan's production rate library, as the workbook gives it:",
        " * landscaping_production_rates.xlsx, sheets \"Production Rates\" and",
        " * \"Logistics\". Generated by scripts/production-rates-seed.py; edit the",
        " * workbook and run it again rather than editing this file.",
        " *",
        " * Every rate is a provisional assumption for ONE person, not a verified",
        " * industry average. Labour minutes = quantity ÷ units per labour-minute;",
        " * crew clock minutes = labour minutes ÷ crew size only when the work",
        " * splits evenly. The variables page overrides any of them once saved.",
        " */",
        "",
        'export type RateUnit = "SF" | "LF" | "EA" | "CY" | "TON";',
        "",
        "export interface ProductionRateSeed {",
        "  /** \"bed-preparation.light-weed-removal\": category and task, so a task listed under two categories stays two rows. */",
        "  key: string;",
        "  category: string;",
        "  task: string;",
        "  unit: RateUnit;",
        "  /** Units one person gets done in a minute of labour. */",
        "  unitsPerLaborMinute: number;",
        "}",
        "",
        f"/** All {len(rates)} rows of the Production Rates sheet, in its order. */",
        "export const PRODUCTION_RATES_SEED: ProductionRateSeed[] = [",
    ]
    for r in rates:
        lines.append(
            f"  {{ key: {json.dumps(r['key'])}, category: {json.dumps(r['category'])}, task: {json.dumps(r['task'])}, unit: {json.dumps(r['unit'])}, unitsPerLaborMinute: {r['unitsPerLaborMinute']:g} }},"
        )
    lines += [
        "];",
        "",
        "export interface LogisticsSeed {",
        "  task: string;",
        "  measurement: string;",
        "  /** Null where the sheet says to measure the actual time. */",
        "  minutes: number | null;",
        "  notes: string;",
        "}",
        "",
        "/** The Logistics sheet as written. */",
        "export const LOGISTICS_SEED: LogisticsSeed[] = [",
    ]
    for l in logistics:
        minutes = "null" if l["minutes"] is None else f"{float(l['minutes']):g}"
        lines.append(
            f"  {{ task: {json.dumps(l['task'])}, measurement: {json.dumps(l['measurement'])}, minutes: {minutes}, notes: {json.dumps(l['notes'])} }},"
        )
    lines += ["];", ""]
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"{len(rates)} rates, {len(logistics)} logistics rows -> {out}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "/mnt/project-files/pricing/landscaping_production_rates.xlsx", sys.argv[2] if len(sys.argv) > 2 else "src/lib/production-rates-seed.ts")
