/** Ray casting. Points exactly on the line count as inside, near enough. */
export function insideHarford(lat: number, lng: number): boolean {
  let inside = false;
  const n = HARFORD_RING.length;
  for (let i = 0, j = n - 1; i < n; j = i, i += 1) {
    const [yi, xi] = HARFORD_RING[i];
    const [yj, xj] = HARFORD_RING[j];
    const crosses = yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi;
    if (crosses) inside = !inside;
  }
  return inside;
}
